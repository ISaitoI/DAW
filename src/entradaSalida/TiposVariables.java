package entradaSalida;

public class TiposVariables {
	public static void main(String[] args) {

		// Dfinimos variables de tipo entero
		byte numeroMuyPequeño = 35;
		short numeroPequeño = 3550;

		// Ademas de declarar, le podemos dar un valor inicial
		int numeroEstandar = 355000000;
		long numeroGrande;

		// Para variables numericas decimales
		float decimalPequeño = 3.15F;
		double decimalGrande = 3.15;

		// Existen vasriables que permiten guardar caracteres
		char caracter1 = 'p';
		char caracter2 = 'J';
		char caracter3 = '3';
		char caracter4 = ':';

		// Hay variabels logicas se usan mucho en bulcles y condicionales
		boolean verdadero = true;
		boolean falso = false;

		// Aunque no sea un tipo basico, metemos aqui al string
		String cadena = "Hola, soy una candena de caracteres";
	}

}
